import 'package:flutter/services.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../data/models/transaction.dart';
import 'time_format_service.dart';

class CertificatePdfService {
  static const _logoPath = 'assets/AppIogo/app_logo.jpeg';
  static const _backgroundPath = 'assets/images/certificate_background.png';

  Future<Uint8List> build(TransactionDetail detail) async {
    final doc = pw.Document();
    final logoData = await rootBundle.load(_logoPath);
    final backgroundData = await rootBundle.load(_backgroundPath);
    final logo = pw.MemoryImage(logoData.buffer.asUint8List());
    final background = pw.MemoryImage(backgroundData.buffer.asUint8List());
    final participants = detail.members
        .map((member) => member.fullName.trim())
        .where((name) => name.isNotEmpty)
        .toList();
    final participantText = participants.isEmpty
        ? 'Registered devotee'
        : participants.join(', ');
    final certificateDate = _firstNonEmpty([
      detail.completedAt,
      detail.date,
      detail.createdAt,
      detail.initiatedAt,
    ]);

    doc.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4.landscape,
        margin: pw.EdgeInsets.zero,
        build: (context) {
          return pw.Stack(
            children: [
              pw.Positioned.fill(
                child: pw.Image(background, fit: pw.BoxFit.cover),
              ),
              pw.Positioned(
                left: 112,
                right: 112,
                top: 42,
                bottom: 42,
                child: pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.stretch,
                  children: [
                    _brandHeader(logo),
                    pw.SizedBox(height: 34),
                    pw.Text(
                      'Certificate of Completion',
                      textAlign: pw.TextAlign.center,
                      style: pw.TextStyle(
                        fontSize: 31,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColor.fromHex('#9B4A08'),
                      ),
                    ),
                    pw.SizedBox(height: 16),
                    pw.Text(
                      'This is to certify that',
                      textAlign: pw.TextAlign.center,
                      style: pw.TextStyle(
                        fontSize: 13,
                        color: PdfColor.fromHex('#7A5B2C'),
                      ),
                    ),
                    pw.SizedBox(height: 8),
                    pw.Text(
                      participantText,
                      textAlign: pw.TextAlign.center,
                      maxLines: 2,
                      style: pw.TextStyle(
                        fontSize: 23,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColor.fromHex('#2B2118'),
                      ),
                    ),
                    pw.SizedBox(height: 12),
                    pw.Text(
                      'has completed the booking for',
                      textAlign: pw.TextAlign.center,
                      style: pw.TextStyle(
                        fontSize: 13,
                        color: PdfColor.fromHex('#7A5B2C'),
                      ),
                    ),
                    pw.SizedBox(height: 8),
                    pw.Text(
                      detail.name.isEmpty ? 'Puja Service' : detail.name,
                      textAlign: pw.TextAlign.center,
                      maxLines: 2,
                      style: pw.TextStyle(
                        fontSize: 21,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColor.fromHex('#2B2118'),
                      ),
                    ),
                    pw.Spacer(),
                    _detailsBox(detail, certificateDate),
                    pw.SizedBox(height: 12),
                    pw.Text(
                      'Generated by Puja Experts using booking records available in the app.',
                      textAlign: pw.TextAlign.center,
                      style: pw.TextStyle(
                        fontSize: 8.5,
                        color: PdfColor.fromHex('#8A6A3E'),
                      ),
                    ),
                  ],
                ),
              ),
            ],
          );
        },
      ),
    );

    return doc.save();
  }

  String fileName(TransactionDetail detail) {
    final source = detail.name.isEmpty ? 'puja-certificate' : detail.name;
    final slug = source
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-z0-9]+'), '-')
        .replaceAll(RegExp(r'^-|-$'), '');
    final id = detail.id.isEmpty ? 'booking' : detail.id;
    return '${slug.isEmpty ? 'puja-certificate' : slug}-$id.pdf';
  }

  pw.Widget _brandHeader(pw.ImageProvider logo) {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.center,
      children: [
        pw.Container(
          width: 42,
          height: 42,
          padding: const pw.EdgeInsets.all(3),
          decoration: pw.BoxDecoration(
            color: const PdfColor(1, 1, 1, 0.78),
            borderRadius: pw.BorderRadius.circular(10),
            border: pw.Border.all(color: PdfColor.fromHex('#E5C36A')),
          ),
          child: pw.ClipRRect(
            horizontalRadius: 7,
            verticalRadius: 7,
            child: pw.Image(logo, fit: pw.BoxFit.cover),
          ),
        ),
        pw.SizedBox(width: 10),
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(
              'Puja Experts',
              style: pw.TextStyle(
                fontSize: 18,
                fontWeight: pw.FontWeight.bold,
                color: PdfColor.fromHex('#2B2118'),
              ),
            ),
            pw.Text(
              'Puja Booking Certificate',
              style: pw.TextStyle(
                fontSize: 9,
                color: PdfColor.fromHex('#8A6A3E'),
              ),
            ),
          ],
        ),
      ],
    );
  }

  pw.Widget _detailsBox(TransactionDetail detail, String certificateDate) {
    final items = <pw.Widget>[
      _detailChip(
        'Status',
        detail.status.isEmpty ? 'Completed' : detail.status,
      ),
      _detailChip('Certificate Date', _formatDateTime(certificateDate)),
      if (detail.location.isNotEmpty) _detailChip('Location', detail.location),
      if (detail.orderId.isNotEmpty) _detailChip('Order ID', detail.orderId),
      if (detail.paymentId.isNotEmpty)
        _detailChip('Payment ID', detail.paymentId),
      _detailChip(
        'Receipt ID',
        detail.receiptId.isEmpty ? detail.id : detail.receiptId,
      ),
      _detailChip('Total Amount', 'INR ${detail.total}'),
    ];

    return pw.Container(
      padding: const pw.EdgeInsets.symmetric(horizontal: 16, vertical: 12),
      decoration: pw.BoxDecoration(
        color: const PdfColor(1, 0.98, 0.92, 0.84),
        borderRadius: pw.BorderRadius.circular(12),
        border: pw.Border.all(color: PdfColor.fromHex('#D9A441'), width: 0.8),
      ),
      child: pw.Wrap(spacing: 10, runSpacing: 8, children: items),
    );
  }

  pw.Widget _detailChip(String label, String value) {
    return pw.Container(
      width: 280,
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.SizedBox(
            width: 82,
            child: pw.Text(
              label,
              style: pw.TextStyle(
                fontSize: 8.5,
                color: PdfColor.fromHex('#7A5B2C'),
              ),
            ),
          ),
          pw.Expanded(
            child: pw.Text(
              value.isEmpty ? '-' : value,
              maxLines: 2,
              style: pw.TextStyle(
                fontSize: 9.5,
                fontWeight: pw.FontWeight.bold,
                color: PdfColor.fromHex('#2B2118'),
              ),
            ),
          ),
        ],
      ),
    );
  }

  String _formatDateTime(String value) {
    if (value.isEmpty) return '-';
    final formatted = TimeFormatService.formatDateTime(value);
    return formatted == '-' ? value : formatted;
  }

  String _firstNonEmpty(List<String> values) {
    for (final value in values) {
      if (value.trim().isNotEmpty) return value;
    }
    return '';
  }
}
